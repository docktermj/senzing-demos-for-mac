#!/usr/bin/env python3
"""Write a source's Module 5 Step 18 documentation and mark it complete in the registry.

Usage: python3 -I src/scripts/write_mapping_docs.py <notes.json>

<notes.json> carries: data_source, source_file, output_file, program, entry_class, entity_type,
records_in, records_out, quality, counts {feature, payload, ignored}, decisions [..],
quality_notes [..], corrections [..], renames [..], filters [..], record_type_check.
Field rows come from data/mapping/<lower>_mapping_spec.json. Writes:
  docs/mapping/<DS>_mapper.md, docs/mapping/mapping_<lower>.md,
  docs/mapping/transformation_lineage_<lower>.md
and updates config/data_sources.yaml (file_path -> output, source_file_path, mapping_status complete).
"""
import datetime
import hashlib
import json
import re
import sys

n = json.load(open(sys.argv[1]))
ds, low = n["data_source"], n["data_source"].lower()
ts = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
spec = json.load(open(f"data/mapping/{low}_mapping_spec.json"))
rows = "\n".join(f"| `{f['source_field']}` | {('`' + f['attribute'] + '`') if f['attribute'] else '—'} | "
                 f"{f['disposition']} | {f['note']} |" for f in spec["fields"])
bullets = lambda items: "\n".join(f"- {i}" for i in items) or "- none"
c = n["counts"]
open(f"docs/mapping/{ds}_mapper.md", "w").write(f"""# Mapping Specification: {ds}

**Source file:** {n['source_file']}
**Data source name:** {ds}
**Entity type:** {n['entity_type']}
**Generated by:** mapping_workflow (Senzing MCP server, {ts[:10]})
**Transformation program:** {n['program']} (shared SenzingJsonPassThrough.java)
**Load-ready output:** {n['output_file']} ({n['records_out']} records)

## Field Mappings

| Source Field | Senzing Attribute | Transformation | Notes |
|---|---|---|---|
{rows}

## Mapping Decisions

{bullets(n['decisions'])}

## Record Corrections

{bullets(n['corrections'])}

## Quality Notes

{bullets(n['quality_notes'])}

## Record Type Check

{n['record_type_check']}
""")
open(f"docs/mapping/mapping_{low}.md", "w").write(f"""# {ds} transformation

- **Reads:** `{n['source_file']}` ({n['records_in']} records, Senzing JSON)
- **Writes:** `{n['output_file']}` ({n['records_out']} records); sample `data/mapping/{low}_sample.jsonl`
- **Program:** `{n['program']}` → shared `src/transform/SenzingJsonPassThrough.java`, JSON via `src/server/MiniJson.java`
- **Mapping:** `docs/mapping/{ds}_mapper.md`; analyzer report `docs/mapping/{ds}_analysis.md`
- **Quality:** {n['quality']}; analyzer clean (no structural or critical errors); verbatim check passes

## How to run

```bash
source src/scripts/senzing-env.sh
javac -d data/temp/transform_classes src/server/MiniJson.java src/transform/SenzingJsonPassThrough.java {n['program']}
src/scripts/run-java.sh data/temp/transform_classes {n['entry_class']} {n['source_file']} -o {n['output_file']}
```
""")
h = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()[:16]
open(f"docs/mapping/transformation_lineage_{low}.md", "w").write(f"""# Transformation Lineage: {ds}

| | File | Records | sha256 |
|---|---|---|---|
| Source | {n['source_file']} | {n['records_in']} | {h(n['source_file'])}… |
| Output | {n['output_file']} | {n['records_out']} | {h(n['output_file'])}… |

- **Program:** {n['program']} (shared SenzingJsonPassThrough.java), {ts[:10]}
- **Field mappings:** see docs/mapping/{ds}_mapper.md ({c['feature']} feature, {c['payload']} payload, {c['ignored']} ignored)
- **Format changes:** none; every emitted value is verbatim from the source
- **Renames:** {', '.join(n['renames']) or 'none'}
- **Filters:** {', '.join(n['filters']) or 'none'}
- **Corrections:** {'; '.join(n['corrections']) or 'none'}
- **Records in / out / rejected:** {n['records_in']} / {n['records_out']} / {n['records_in'] - n['records_out']}
""")
p = "config/data_sources.yaml"
t = open(p).read()
blk = re.search(rf"(  {ds}:\n(?:    .*\n|      .*\n)*)", t).group(1)
nb = re.sub(r"    file_path: \S+\n", f"    file_path: {n['output_file']}\n", blk, count=1)
if "source_file_path:" not in nb:
    nb = nb.replace(f"    file_path: {n['output_file']}\n",
                    f"    file_path: {n['output_file']}\n    source_file_path: {n['source_file']}  # mapped input\n"
                    f"    transformation: {n['program']}\n    mapping_spec: docs/mapping/{ds}_mapper.md\n", 1)
nb = re.sub(r"    mapping_status: \w+", "    mapping_status: complete", nb)
nb = re.sub(r'    updated_at: ".*"', f'    updated_at: "{ts}"', nb)
open(p, "w").write(t.replace(blk, nb))
print("documented", ds)
