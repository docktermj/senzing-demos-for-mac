#!/usr/bin/env python3
"""Generate the Java visualization server's front-end assets from the bootcamp reference.

The visualization page (HTML/CSS/D3 JavaScript) runs in the browser, so it is the same
whatever language the server is written in. Rather than hand-writing it, this generator
takes the page template from the bootcamp's shipped reference server
(scripts/senzing_viz_server.py, its PAGE constant) and copies the vendored D3 v7 next to
it, so the Java server (src/server/VizServer.java) serves the identical front-end and
renders fully offline.

Usage (from the project root):
    python3 src/scripts/extract_viz_page.py <plugin-scripts-dir>

Writes:
    src/server/resources/page.html             the page template, placeholders intact
    src/server/resources/vendor/d3.v7.min.js   the vendored D3 (never fetched from a CDN)
"""
import importlib.util
import os
import shutil
import sys


def main(argv):
    if len(argv) != 2:
        sys.stderr.write(__doc__)
        return 2
    scripts_dir = argv[1]
    ref = os.path.join(scripts_dir, "senzing_viz_server.py")
    d3 = os.path.join(scripts_dir, "vendor", "d3.v7.min.js")
    for path in (ref, d3):
        if not os.path.isfile(path):
            sys.stderr.write(f"missing: {path}\n")
            return 1

    spec = importlib.util.spec_from_file_location("senzing_viz_server_ref", ref)
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, scripts_dir)
    spec.loader.exec_module(mod)
    page = mod.PAGE

    out_dir = os.path.join("src", "server", "resources")
    os.makedirs(os.path.join(out_dir, "vendor"), exist_ok=True)
    first, rest = page.split("\n", 1)
    banner = ("<!-- Generated by src/scripts/extract_viz_page.py from the bootcamp reference "
              "scripts/senzing_viz_server.py (PAGE). Do not edit by hand; regenerate. -->")
    with open(os.path.join(out_dir, "page.html"), "w", encoding="utf-8") as fh:
        fh.write(first + "\n" + banner + "\n" + rest)
    shutil.copyfile(d3, os.path.join(out_dir, "vendor", "d3.v7.min.js"))
    print("wrote src/server/resources/page.html and src/server/resources/vendor/d3.v7.min.js")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
